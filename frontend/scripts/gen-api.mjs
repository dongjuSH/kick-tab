// Generates src/lib/api/schema.d.ts from the backend OpenAPI document.
// Usage: npm run gen:api            (reads ${BACKEND_ORIGIN:-http://localhost:8000}/openapi.json)
//        npm run gen:api -- <file>  (reads a saved openapi.json instead)
import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const origin = (process.env.BACKEND_ORIGIN ?? "http://localhost:8000").replace(/\/+$/, "");
const arg = process.argv[2];
const source = arg ? pathToFileURL(arg) : new URL(`${origin}/openapi.json`);
const output = new URL("../src/lib/api/schema.d.ts", import.meta.url);

const ast = await openapiTS(source);
const header =
  "/**\n * Generated by `npm run gen:api` from the backend OpenAPI document. Do not edit.\n */\n\n";
await writeFile(output, header + astToString(ast));
console.log(`Wrote ${fileURLToPath(output)} from ${arg ?? source.href}`);
